func TestPlacementPolicy(t *testing.T) {
	var generated bytes.Buffer
	if err := ufdr.WriteSynthetic(&generated, 32); err != nil {
		t.Fatal(err)
	}
	fixture := generated.Bytes()
	root, stage := t.TempDir(), t.TempDir()
	calls := 0
	orchestrator := testOrchestrator(func(w http.ResponseWriter, r *http.Request) {
		calls++
		if r.Method != http.MethodPut {
			t.Errorf("unexpected call %s %s", r.Method, r.URL)
			http.Error(w, "unexpected call", 500)
			return
		}
		var request struct {
			Job struct {
				Name        string
				Constraints []struct {
					Key, Operator string
					Values        []string
				}
				Tasks []struct {
					InputSources []struct {
						Target string
						Source struct {
							Type   string
							Params map[string]string
						}
					}
				}
			}
		}
		if err := json.NewDecoder(r.Body).Decode(&request); err != nil {
			t.Error(err)
			http.Error(w, "invalid job request", 500)
			return
		}
		job := request.Job
		if len(job.Constraints) != 1 || job.Constraints[0].Key != "name" || job.Constraints[0].Operator != "in" ||
			len(job.Constraints[0].Values) != 1 || job.Constraints[0].Values[0] != "viii-a" ||
			len(job.Tasks) != 1 || len(job.Tasks[0].InputSources) != 2 {
			t.Errorf("unexpected job shape: %+v", job)
			http.Error(w, "unexpected job shape", 500)
			return
		}
		attempt := job.Name[len("viii-"):]
		source := job.Tasks[0].InputSources[1]
		if source.Target != "/inputs" || source.Source.Type != "urldownload" ||
			source.Source.Params["URL"] != "http://stage/evidence/"+attempt+".xml" {
			t.Errorf("unexpected staged source: %+v", source)
		}
		data, err := os.ReadFile(filepath.Join(stage, attempt+".xml"))
		if err != nil || !bytes.Equal(data, fixture) {
			t.Errorf("staged bytes: %v", err)
		}
		if _, err = (&workbench{root: root}).load(digest(fixture), attempt); err != nil {
			t.Errorf("attempt was not persisted before submission: %v", err)
		}
		w.Write([]byte(`{"JobID":"test-job"}`))
	})
	p := &wasijob.Placement{
		Allow:       map[string]map[string]bool{digest(fixture): {"viii-a": true}},
		Modules:     map[string]string{"viii-a": "http://stage/worker.wasm", "viii-b": "http://stage/worker.wasm"},
		StagingURLs: map[string]string{"viii-a": "http://stage", "viii-b": "http://stage"},
		StagingDir:  stage, WorkerSHA256: "test-worker", Client: orchestrator,
	}
	s := &workbench{root: root}
	for _, tc := range []struct {
		name, node string
		policy     *wasijob.Placement
		input      []byte
	}{
		{"no policy", "viii-b", nil, fixture},
		{"unapproved node", "viii-b", p, fixture},
		{"no node", "", p, fixture},
		{"different evidence", "viii-a", p, bytes.Replace(fixture, []byte("fictional item"), []byte("fictional book"), 1)},
	} {
		t.Run(tc.name, func(t *testing.T) {
			s.placement = tc.policy
			a := callAttempt(t, s, "POST", "/api/process?mode=bacalhau&node="+tc.node, tc.input, 403)
			if a["authorization"] != "deny" || a["job_id"] != nil || calls != 0 {
				t.Fatalf("denial side effect: %v, calls %d", a, calls)
			}
			for _, dir := range []string{root, stage} {
				entries, err := os.ReadDir(dir)
				if err != nil || len(entries) != 0 {
					t.Fatalf("denial wrote files to %s: %v, %v", dir, entries, err)
				}
			}
		})
	}
	s.placement = p
	a := callAttempt(t, s, "POST", "/api/process?mode=bacalhau&node=viii-a", fixture, 202)
	if a["authorization"] != "allow" || a["job_id"] != "test-job" || calls != 1 {
		t.Fatalf("allowed request: %v, calls %d", a, calls)
	}
}

func TestReconcileLostSubmissionResponse(t *testing.T) {
	input := readSpikeFile(t, "../../docs/research/fixtures/ufdr/messages-minimal.xml")
	var name string
	submissions := 0
	orchestrator := testOrchestrator(func(w http.ResponseWriter, r *http.Request) {
		if r.Method == http.MethodPut {
			var request struct{ Job struct{ Name string } }
			if err := json.NewDecoder(r.Body).Decode(&request); err != nil {
				t.Error(err)
				http.Error(w, "bad test request", 500)
				return
			}
			submissions++
			name = request.Job.Name
			// The job exists but the client never received a valid response.
			w.Write([]byte("bad response"))
			return
		}
		if r.URL.Path != "/api/v1/orchestrator/jobs/"+name {
			t.Errorf("unexpected job lookup: %s", r.URL.Path)
		}
		json.NewEncoder(w).Encode(map[string]any{
			"Job": map[string]any{"ID": "test-job", "Name": name, "State": map[string]string{"StateType": "Completed"}},
			"Executions": map[string]any{"Items": []map[string]any{
				{"ID": "test-execution", "NodeID": "unexpected-node", "RunOutput": map[string]any{"Stdout": "{}"}},
			}},
		})
	})
	p := &wasijob.Placement{
		Allow:        map[string]map[string]bool{digest(input): {"viii-a": true}},
		Modules:      map[string]string{"viii-a": "http://stage/worker.wasm"},
		WorkerSHA256: "test-worker", Client: orchestrator,
	}
	s := &workbench{root: t.TempDir(), placement: p}
	url := "/api/process?mode=bacalhau&node=viii-a"
	a := callAttempt(t, s, "POST", url, input, 202)
	if a["status"] != "submitting" || a["job_id"] != nil {
		t.Fatalf("expected uncertain submission: %v", a)
	}
	s = &workbench{root: s.root, placement: p}
	if current := callAttempt(t, s, "POST", url, input, 202); current["attempt"] != a["attempt"] || submissions != 1 {
		t.Fatalf("repeated submission: %v, submissions %d", current, submissions)
	}
	current := callAttempt(t, s, "GET", attemptPath(a), nil, 200)
	if current["status"] != "failed" || current["job_id"] != "test-job" || current["node_id"] != "unexpected-node" ||
		current["execution_id"] != "test-execution" || current["result"] != nil || submissions != 1 {
		t.Fatalf("reconciliation accepted misplaced result or lost provenance: %v", current)
	}
}

type roundTripFunc func(*http.Request) (*http.Response, error)

func (f roundTripFunc) RoundTrip(r *http.Request) (*http.Response, error) { return f(r) }

func testOrchestrator(handler http.HandlerFunc) wasijob.Client {
	return wasijob.Client{Base: "http://orchestrator.invalid", HTTP: &http.Client{
		Transport: roundTripFunc(func(r *http.Request) (*http.Response, error) {
			w := httptest.NewRecorder()
			handler(w, r)
			return w.Result(), nil
		}),
	}}
}
